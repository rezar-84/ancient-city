/** Render narration with ElevenLabs (eleven_multilingual_v2) for landmarks + tour, EN and TR.
 * Skips files that already exist. Then rewrites src/content/audio.ts.
 * Run: npx tsx --env-file=.env.local scripts/tts_elevenlabs.ts [--only=id,id] [--force] */
import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { LANDMARKS } from '../src/content/landmarks.ts'
import { TOUR } from '../src/content/tour.ts'

const KEY = process.env.ELEVENLABS_API_KEY!, VOICE = process.env.ELEVENLABS_VOICE_ID!
if (!KEY || !VOICE) throw new Error('ELEVENLABS_API_KEY / ELEVENLABS_VOICE_ID missing')
const force = process.argv.includes('--force')
const only = process.argv.find((a) => a.startsWith('--only='))?.slice(7).split(',')

type Job = { file: string; text: string; lang: 'en' | 'tr' }
const jobs: Job[] = []
for (const lang of ['en', 'tr'] as const) {
  for (const l of LANDMARKS) {
    if (only && !only.includes(l.id)) continue
    const text = `${l.name[lang]}. ${l.summary[lang]}${l.didYouKnow ? ' ' + (lang === 'en' ? 'Did you know? ' : 'Biliyor muydunuz? ') + l.didYouKnow[lang] : ''}`
    jobs.push({ file: `public/audio/${lang}/${l.id}.mp3`, text, lang })
  }
  for (const s of TOUR) {
    if (only && !only.includes('tour-' + s.id)) continue
    jobs.push({ file: `public/audio/${lang}/tour-${s.id}.mp3`, text: s.text[lang], lang })
  }
}

async function render(j: Job) {
  const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE}?output_format=mp3_44100_96`, {
    method: 'POST',
    headers: { 'xi-api-key': KEY, 'content-type': 'application/json', accept: 'audio/mpeg' },
    body: JSON.stringify({
      text: j.text,
      model_id: 'eleven_multilingual_v2',
      language_code: j.lang,
      voice_settings: { stability: 0.55, similarity_boost: 0.8, style: 0.25, use_speaker_boost: true, speed: 0.95 },
    }),
  })
  if (!res.ok) throw new Error(`${j.file}: ${res.status} ${(await res.text()).slice(0, 300)}`)
  writeFileSync(j.file, Buffer.from(await res.arrayBuffer()))
}

let chars = 0
for (const j of jobs) {
  if (existsSync(j.file) && !force) continue
  chars += j.text.length
  process.stdout.write(`render ${j.file} (${j.text.length} chars)… `)
  try { await render(j); console.log('ok') } catch (e) { console.log('FAILED', (e as Error).message) }
}
console.log('characters sent:', chars)

const files = (['en', 'tr'] as const).flatMap((l) => readdirSync(`public/audio/${l}`).filter((f) => f.endsWith('.mp3')).map((f) => `/audio/${l}/${f}`)).sort()
writeFileSync('src/content/audio.ts', `/** Narration files that exist in public/audio (regenerated by scripts/tts_elevenlabs.ts). */\nexport const AUDIO = new Set<string>(${JSON.stringify(files, null, 2)})\nexport const audioIf = (p: string) => (AUDIO.has(p) ? p : undefined)\n`)
console.log('audio.ts:', files.length, 'files')
