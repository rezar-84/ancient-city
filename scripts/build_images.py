"""Resize research images into public/img and generate src/content/images.ts (photos + archive per landmark, historic maps).
Run: python3 -I scripts/build_images.py"""
import csv, json, os, sys
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, 'research'); OUT = os.path.join(ROOT, 'public', 'img')
os.makedirs(OUT, exist_ok=True)

PHOTO = {'travertines': 'travertines', 'frontinus_gate': 'frontinus-gate', 'plateia': 'frontinus-street', 'north_necropolis': 'necropolis',
         'north_byzantine_gate': 'byzantine-gate-n', 'north_agora': 'agora', 'theatre': 'theatre', 'ploutonion': 'ploutonion',
         'antique_pool': 'antique-pool', 'martyrium_philip': 'martyrium', 'tomb_philip': 'philip-church', 'great_baths_museum': 'baths',
         'nymphaeum_tritons': 'tritons', 'temple_apollo': 'apollo', 'temple_nymphaeum': 'apollo', 'south_byzantine_gate': 'south-gate',
         'city_walls': 'byzantine-gate-n', 'cathedral': 'cathedral', 'latrine': 'latrine', 'stoa_springs': 'antique-pool'}
# archive material (historic plans, engravings, museum artifacts) by file stem
ARCHIVE = {
  'theatre': ['plan_8', 'artifact_1', 'artifact_2', 'artifact_4', 'artifact_3', 'artifact_7', 'artifact_12', 'artifact_15', 'artifact_11'],
  'frontinus-gate': ['plan_9'], 'frontinus-street': ['plan_9'],
  'baths': ['plan_10', 'plan_13'],
  'travertines': ['plan_2', 'plan_11'],
  'ploutonion': ['artifact_5', 'artifact_17', 'artifact_6'],
  'necropolis': ['artifact_13', 'artifact_14', 'artifact_18'],
  'agora': ['artifact_9', 'artifact_10', 'plan_3'],
  'apollo': ['artifact_15'],
}
MAPS = ['plan_1', 'plan_7', 'plan_5', 'plan_6']

rows = list(csv.DictReader(open(os.path.join(R, 'manifest.csv'))))
by_stem = {}
for r in rows:
    f = r['file']
    if not f.startswith('images/'): continue
    stem = os.path.splitext(os.path.basename(f))[0]
    by_stem[stem] = r

def credit(r):
    a = (r['author'] or 'unknown').strip()
    a = a[:60]
    return f"{a} · {r['license']} · via {'Wikimedia Commons' if 'wikimedia' in r['source_url'] else r['source_url'].split('/')[2]}"

def convert(r, maxw=1600):
    src = os.path.join(R, r['file'])
    if not os.path.exists(src): return None
    stem = os.path.splitext(os.path.basename(r['file']))[0]
    dst = os.path.join(OUT, stem + '.jpg')
    if not os.path.exists(dst):
        im = Image.open(src)
        if im.mode in ('RGBA', 'LA', 'P'):
            im = im.convert('RGBA'); bg = Image.new('RGB', im.size, (255, 255, 255)); bg.paste(im, mask=im.split()[-1]); im = bg
        else: im = im.convert('RGB')
        if im.width > maxw: im = im.resize((maxw, round(im.height * maxw / im.width)), Image.LANCZOS)
        im.save(dst, quality=78, optimize=True, progressive=True)
    return f'/img/{stem}.jpg'

def entry(r, kind):
    src = convert(r, 1800 if kind == 'archive' else 1280)
    if not src: return None
    t = r['title'].rsplit('.', 1)[0] if r['title'].lower().endswith(('.jpg', '.jpeg', '.png', '.svg', '.tif')) else r['title']
    return {'src': src, 'credit': credit(r), 'kind': kind, 'title': t[:140], 'url': r['source_url']}

images = {}
for r in rows:
    lid = PHOTO.get(r['landmark_or_type'])
    if lid:
        e = entry(r, 'photo')
        if e: images.setdefault(lid, []).append(e)
for lid, stems in ARCHIVE.items():
    for s in stems:
        if s in by_stem:
            e = entry(by_stem[s], 'archive')
            if e: images.setdefault(lid, []).append(e)
maps = [e for e in (entry(by_stem[s], 'archive') for s in MAPS if s in by_stem) if e]

ts = "import type { Img } from './types'\n/** GENERATED by scripts/build_images.py from research/manifest.csv — do not edit by hand. */\n"
ts += f"export const IMAGES: Record<string, Img[]> = {json.dumps(images, ensure_ascii=False, indent=1)}\n"
ts += f"export const HISTORIC_MAPS: Img[] = {json.dumps(maps, ensure_ascii=False, indent=1)}\n"
open(os.path.join(ROOT, 'src', 'content', 'images.ts'), 'w').write(ts)
total = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
print({k: len(v) for k, v in images.items()}, 'maps', len(maps), f'{total/1e6:.1f} MB')
