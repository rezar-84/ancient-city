"""Generate src/content/ruins.ts — archaeological footprints and secondary labels for the plan, from OSM (ODbL).
Run: python3 -I scripts/build_ruins.py"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
G = os.path.join(ROOT, 'research', 'geo')
SKIP_NAMES = {'Hierapolis', 'Northern Necropolis of Hierapolis', 'Eastern Necropolis', 'Southern Necropolis', 'Necropolis'}
TR = {
  'Stoa Basilica': 'Stoa-Bazilika', 'Gymnasium': 'Gymnasion', 'Gymnasium portico': 'Gymnasion revakı', 'Octagonal Baths': 'Sekizgen Hamam',
  'Suburban Greek Theatre': 'Kent dışı Grek Tiyatrosu', 'Church of the Sepulchre': 'Mezar Kilisesi', 'Agiasma (Sanctuary Fountain)': 'Ayazma (Kutsal Çeşme)',
  'Baptistery': 'Vaftizhane', 'Central Baths': 'Merkezi Hamam', 'South Basilica': 'Güney Bazilika', 'Roman Baths': 'Roma Hamamı',
  'House with the Ionic Columns': 'İon Sütunlu Ev', 'Baths - Basilica': 'Hamam-Bazilika', 'Byzantine small church and cemetery': 'Küçük Bizans kilisesi ve mezarlık',
  'Tomb of Flavius Zeuxis and his sons (1st': 'Flavius Zeuxis ve oğullarının mezarı', 'Tumulus 51 (1st century AD)': 'Tümülüs 51 (MS 1. yy)',
  'Church': 'Kilise', 'Monumental Nymphaeum': 'Anıtsal Nymphaeum', 'Seldjuk Fortress Wall': 'Selçuklu kalesi', 'East Gate': 'Doğu Kapısı',
  'St. Philip Gate': 'Aziz Philippos Kapısı', 'Aurelius Ammianus Menandrianus': 'Aurelius Ammianus Menandrianus', 'Tomb A18': 'Mezar A18',
}
EN = {'Seldjuk Fortress Wall': 'Seljuk fortress', 'Tomb of Flavius Zeuxis and his sons (1st': 'Tomb of Flavius Zeuxis', 'Baths - Basilica': 'Bath-basilica'}
LABEL_KEEP = set(TR)  # names worth a small label on the plan (main monuments have numbered pins)

def r5(c): return [round(c[1], 6), round(c[0], 6)]
shapes, labels, seen = [], [], set()
for fname in ('archaeology.geojson', 'city_walls.geojson', 'necropolis.geojson', 'ancient_streets.geojson'):
    for f in json.load(open(os.path.join(G, fname)))['features']:
        p, g = f['properties'], f['geometry']
        key = json.dumps(g['coordinates'])[:200]
        if key in seen: continue
        seen.add(key)
        name = (p.get('name:en') or p.get('name') or '').strip()
        if name in SKIP_NAMES: continue
        kind = 'tower' if p.get('historic') in ('tower',) or p.get('man_made') == 'tower' else \
               'tomb' if p.get('historic') in ('tomb',) else \
               'gate' if p.get('historic') == 'city_gate' else \
               'wall' if p.get('historic') == 'citywalls' or 'Wall' in name else 'ruin'
        if g['type'] == 'Polygon': rings = [g['coordinates'][0]]
        elif g['type'] == 'MultiPolygon': rings = [q[0] for q in g['coordinates']]
        elif g['type'] == 'LineString': rings = [g['coordinates']]
        else: rings = []
        for r in rings:
            if len(r) >= 2: shapes.append({'k': kind, 'c': g['type'] != 'LineString', 'p': [r5(c) for c in r]})
        if name in LABEL_KEEP:
            pts = rings[0] if rings else [g['coordinates']]
            lat = sum(c[1] for c in pts) / len(pts); lon = sum(c[0] for c in pts) / len(pts)
            labels.append({'en': EN.get(name, name), 'tr': TR[name], 'lat': round(lat, 6), 'lon': round(lon, 6)})
ts = "/** GENERATED by scripts/build_ruins.py from OpenStreetMap archaeological mapping (ODbL) — do not edit. */\n"
ts += "export type RuinShape = { k: 'ruin' | 'tower' | 'tomb' | 'gate' | 'wall'; c: boolean; p: Array<[number, number]> }\n"
ts += f"export const RUINS: RuinShape[] = {json.dumps(shapes, separators=(',', ':'))}\n"
ts += "export const RUIN_LABELS: Array<{ en: string; tr: string; lat: number; lon: number }> = " + json.dumps(labels, ensure_ascii=False, indent=1) + "\n"
open(os.path.join(ROOT, 'src', 'content', 'ruins.ts'), 'w').write(ts)
print(len(shapes), 'shapes', len(labels), 'labels', round(len(ts) / 1024), 'KB')
