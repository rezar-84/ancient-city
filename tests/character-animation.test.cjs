const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const vm = require('node:vm')
const ts = require('typescript')
const THREE = require('three')
const context = { exports: {} }
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/walk/anim.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, context)
const { PoseBlender } = context.exports

test('blend endpoints, independent instances, and queued interruption continuity', () => {
  const b = new PoseBlender(2)
  const pose = new THREE.InstancedBufferAttribute(new Float32Array(4), 2)
  const anim = new THREE.InstancedBufferAttribute(new Float32Array(8), 4)
  b.write(pose, 0, 0, anim)
  assert.equal(pose.getY(0), 1)
  b.set(0, 6, 1)
  b.write(pose, 0, 1, anim)
  assert.equal(pose.getX(0), 0)
  assert.equal(pose.getY(0), 0)
  assert.equal(anim.getZ(0), 6)
  b.write(pose, 0, 1.15, anim)
  assert.ok(Math.abs(pose.getY(0) - 0.5) < 1e-6)
  b.set(0, 8, 1.15)
  assert.equal(b.write(pose, 0, 1.15, anim), 6)
  assert.ok(Math.abs(pose.getY(0) - 0.5) < 1e-6)
  assert.equal(b.write(pose, 0, 1.31, anim), 8)
  assert.equal(pose.getX(0), 6)
  assert.equal(pose.getY(0), 0)
  b.write(pose, 0, 2, anim)
  assert.equal(pose.getY(0), 1)
  assert.equal(b.write(pose, 1, 2, anim), 0)
  assert.equal(pose.getY(1), 1)
  b.set(0, 8, 3)
  b.write(pose, 0, 3)
  assert.equal(pose.getY(0), 1)
})

test('invalid configuration and inputs are rejected', () => {
  assert.throws(() => new PoseBlender(-1), /Invalid/)
  assert.throws(() => new PoseBlender(1, 0, 0), /Invalid/)
  const b = new PoseBlender(1)
  assert.throws(() => b.set(1, 0, 0), /Invalid/)
  assert.throws(() => b.set(0, 11, 0), /Invalid/)
  assert.throws(() => b.set(0, 1, NaN), /Invalid/)
})
